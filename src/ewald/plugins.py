def _contribute(kind: str, name: str):
    """Record ``name`` as a contribution of the plugin being loaded (see :func:`installed`)."""
    plugin = _loading.plugin
    if plugin is not None and name not in plugin.contributions.setdefault(kind, []):
        plugin.contributions[kind].append(name)


# ewald's own formats, grouped like VS Code's built-in extensions: always installed, listed by
# :func:`installed` with kind "built-in", and switched off with :func:`set_enabled` (their readers
# and writers leave the registries; ASE may still read some of those files). Formats outside
# these groups (extxyz, the ASE fallback) are core and cannot be switched off.
BUILTIN_PLUGINS = {
    "vasp": ("VASP", "POSCAR/CONTCAR, XDATCAR, OUTCAR, vasprun.xml, vaspout.h5, CHGCAR/LOCPOT/ELFCAR "
             "and NEB folders",
             ("neb", "vasp-volumetric", "vaspout", "vaspwave", "xdatcar", "outcar", "vasprun"),
             ("vasp-volumetric", "poscar", "xdatcar")),
    "lammps": ("LAMMPS", "LAMMPS text dumps and data files",
               ("lammps-dump", "lammps-data", "lammps-data-ase"), ("lammps-dump", "lammps-data")),
    "cube": ("Gaussian cube", "Volumetric data in Gaussian cube files", ("cube",), ("cube",)),
    "md-formats": ("MD trajectories", "GROMACS XTC/TRR, DCD, AMBER NetCDF, H5MD and MDTraj HDF5",
                   ("md-trajectory", "h5md", "mdtraj-h5"), ("md-trajectory", "h5md")),
    "xsf": ("XCrySDen XSF", "XSF/AXSF structures, trajectories and 3D grids", ("xsf",), ("xsf",)),
    "ase-formats": ("ASE files", "ASE databases (.db) and trajectories (.traj), and CIF via ASE",
                    ("ase-db", "ase-traj", "cif"), ("ase-db", "ase-traj", "cif")),
}


def _load_builtin(off: set):
    """List the built-in plugins and drop the formats of the disabled ones."""
    version = ewald_version()
    for pid, (name, description, reader_names, writer_names) in BUILTIN_PLUGINS.items():
        plugin = Plugin(id=pid, name=name, version=version, description=description, publisher="ewald",
                        kind="built-in", origin="built-in")
        if pid in off:
            plugin.enabled = False
        for registry, kind, names in ((_registry.readers, "readers", reader_names),
                                      (_registry.writers, "writers", writer_names)):
            present = [n for n in names if n in registry and registry[n].origin == "built-in"]
            if plugin.enabled:
                if present:
                    plugin.contributions[kind] = present
            else:
                for n in present:
                    del registry[n]
        plugin.loaded = plugin.enabled
        _registry.plugins[pid] = plugin


def _state_path() -> Path:
    from .settings import config_dir

    return config_dir() / "plugins.json"


def disabled() -> set[str]:
    """Ids of the plugins switched off with :func:`set_enabled` (kept in ``<config dir>/plugins.json``)."""
    try:
        return set(json.loads(_state_path().read_text(encoding="utf-8")).get("disabled", []))
    except (OSError, ValueError, AttributeError):
        return set()


def set_enabled(plugin_id: str, enabled: bool = True, reload: bool = True):
    """Switch a plugin on or off for every later session, and (``reload``) reload the plugins now.

    A disabled plugin is still listed by :func:`installed` but none of its code is imported.
    A package that was already imported stays in memory until restart, but its readers,
    modifiers and other contributions leave the registries.
    """
    path = _state_path()
    try:
        state = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        state = {}
    off = set(state.get("disabled", []))
    if enabled:
        off.discard(plugin_id)
    else:
        off.add(plugin_id)
    state["disabled"] = sorted(off)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(state, indent=1) + "\n", encoding="utf-8")
    if reload:
        load_plugins(force=True)


def installed() -> dict[str, Plugin]:
    """Installed plugins by id: ewald's built-in format groups (:data:`BUILTIN_PLUGINS`), pip
    packages and plugin-folder files, including disabled, incompatible and failed ones, with what
    each contributed."""
    load_plugins()
    return dict(_registry.plugins)


def _admit(plugin: Plugin, off: set) -> bool:
    """Record ``plugin`` and decide whether its code may be imported."""
    if plugin.id in _registry.plugins:
        plugin.errors.append(f"plugin id {plugin.id!r} is also used by {_registry.plugins[plugin.id].origin}")
        _registry.errors[plugin.origin] = plugin.errors[-1]
        _registry.plugins[f"{plugin.id}@{plugin.origin}"] = plugin
        return False
    _registry.plugins[plugin.id] = plugin
    if plugin.id in off:
        plugin.enabled = False
        return False
    from .plugin_api import check

    problem = check(plugin.plugin_api)
    if problem:
        plugin.compatible = False
        plugin.errors.append(problem)
        _registry.errors[plugin.origin] = problem
        return False
    if plugin.requires_ewald:
        try:
            plugin.compatible = version_satisfies(ewald_version(), plugin.requires_ewald)
            problem = "" if plugin.compatible else \
                f"needs ewald {plugin.requires_ewald}; this is ewald {ewald_version()}"
        except ValueError as exc:
            plugin.compatible, problem = False, str(exc)
        if problem:
            plugin.errors.append(problem)
            _registry.errors[plugin.origin] = problem
            return False
    return True


def load_plugins(force: bool = False):
    """Import entry points and files in :func:`plugin_dir` once per process (``force`` reloads)."""
    if _registry.loaded and not force:
        return
    _registry.loaded = True
    if force:
        keep = {k: v for k, v in _registry.readers.items() if v.origin == "python"}
        _registry.readers = {**_builtin_readers(), **keep}
        _registry.modifiers = {k: v for k, v in _registry.modifiers.items() if v.origin == "python"}
        keep = {k: v for k, v in _registry.writers.items() if v.origin == "python"}
        _registry.writers = {**_builtin_writers(), **keep}
        keep = {k: v for k, v in _registry.visuals.items() if v.origin == "python" and not v.builtin}
        _registry.visuals = {**_builtin_visuals(), **keep}
        keep = {k: v for k, v in _registry.overlays.items() if v.origin == "python" and not v.builtin}
        _registry.overlays = {**_builtin_overlays(), **keep}
        _registry.colormaps = {k: v for k, v in _registry.colormaps.items() if v.origin == "python"}
        keep = {k: v for k, v in _registry.themes.items() if v.origin == "python" and not v.builtin}
        _registry.themes = {**_builtin_themes(), **keep}
        _registry.tools = {k: v for k, v in _registry.tools.items() if v.origin == "python"}
        keep = {k: v for k, v in _registry.ui_themes.items() if v.origin == "python" and not v.builtin}
        _registry.ui_themes = {**_builtin_ui_themes(), **keep}
        keep = {k: v for k, v in _registry.ai_providers.items() if v.origin == "python"}
        _registry.ai_providers = {**_builtin_ai_providers(), **keep}
        _registry.panels = {k: v for k, v in _registry.panels.items() if v.origin == "python"}
        _registry.menu_items = {k: v for k, v in _registry.menu_items.items() if v.origin == "python"}
        _registry.settings_pages = {k: v for k, v in _registry.settings_pages.items() if v.origin == "python"}
        _registry.workflows = {k: v for k, v in _registry.workflows.items() if v.origin == "python"}
        _registry.errors.clear()
        _registry.plugins = {}
    off = disabled()
    _load_builtin(off)
    if os.environ.get("EWALD_NO_PLUGINS"):
        return
    _load_entry_points(off)
    _load_directory(plugin_dir(), off)


def _dist_key(ep) -> str:
    dist = getattr(ep, "dist", None)
    return dist.name if dist is not None else ep.value.split(":")[0].split(".")[0]


def _package_manifest(value: str) -> dict:
    """``ewald-plugin.toml`` next to the module or inside the package ``value`` (an
    ``ewald.plugins`` entry point), located with ``find_spec`` so no plugin code runs."""
    spec = importlib.util.find_spec(value.split(":")[0])
    if spec is None:
        raise ModuleNotFoundError(f"no module named {value!r}")
    if spec.submodule_search_locations:
        folder = Path(list(spec.submodule_search_locations)[0])
    elif spec.origin:
        folder = Path(spec.origin).parent
    else:
        return {}
    path = folder / MANIFEST_NAME
    return _read_toml(path) if path.is_file() else {}


def _entry_point_scan():
    """``entry_points(group=...)`` over one scan of the installed distributions: scanning once
    per group (15 groups) cost about 0.1 s at every start."""
    from importlib.metadata import entry_points

    everything = entry_points()
    return lambda group: everything.select(group=group)


def _load_entry_points(off: set = frozenset()):
    entry_points = _entry_point_scan()
    found = {}    # distribution -> [(register, entry point)]
    for group, register in ((READER_GROUP, lambda name, obj: register_reader(name, obj)),
                            (MODIFIER_GROUP, lambda name, obj: register_modifier(obj, name=name)),
                            (WRITER_GROUP, lambda name, obj: register_writer(name, obj)),
                            (VISUAL_GROUP, lambda name, obj: register_visual(obj, name=name)),
                            (OVERLAY_GROUP, lambda name, obj: register_overlay(obj, name=name)),
                            (COLORMAP_GROUP, lambda name, obj: register_colormap(name, obj)),
                            (THEME_GROUP, lambda name, obj: register_theme(name, obj)),
                            (TOOL_GROUP, lambda name, obj: register_tool(name, obj)),
                            (UI_THEME_GROUP, lambda name, obj: register_ui_theme(name, obj)),
                            (AI_PROVIDER_GROUP, lambda name, obj: register_ai_provider(name, obj)),
                            (PANEL_GROUP, lambda name, obj: register_panel(name, obj)),
                            (MENU_ITEM_GROUP, lambda name, obj: register_menu_item(name, obj)),
                            (SETTINGS_PAGE_GROUP, lambda name, obj: register_settings_page(name, obj)),
                            (WORKFLOW_GROUP, lambda name, obj: register_workflow_source(name, obj))):
        try:
            eps = entry_points(group=group)
        except Exception as exc:
            _registry.errors[group] = str(exc)
            continue
        for ep in eps:
            found.setdefault(_dist_key(ep), []).append((register, ep))
    try:
        manifests = {_dist_key(ep): ep for ep in entry_points(group=PLUGIN_GROUP)}
    except Exception as exc:
        _registry.errors[PLUGIN_GROUP] = str(exc)
        manifests = {}
    for key in manifests:
        found.setdefault(key, [])
    for key, items in found.items():
        some = manifests.get(key) or items[0][1]
        dist = getattr(some, "dist", None)
        plugin = Plugin(id=manifests[key].name if key in manifests else key, kind="package", origin=key,
                        version=dist.version if dist is not None else "")
        if dist is not None:
            plugin.description = dist.metadata.get("Summary") or ""
        if key in manifests:
            try:
                plugin.apply_manifest(_package_manifest(manifests[key].value))
            except Exception as exc:
                plugin.errors.append(f"manifest: {type(exc).__name__}: {exc}")
                _registry.errors[f"manifest of {key}"] = plugin.errors[-1]
        if not _admit(plugin, off):
            continue
        for register, ep in items:
            origin = f"entry point {ep.value}"
            try:
                _loading.origin, _loading.plugin = origin, plugin   # also for decorators run by the import
                obj = ep.load()
                register(ep.name, obj)
            except Exception as exc:
                _registry.errors[origin] = f"{type(exc).__name__}: {exc}"
                plugin.errors.append(f"{ep.name}: {type(exc).__name__}: {exc}")
            finally:
                _loading.origin = _loading.plugin = None
        plugin.loaded = True


def _load_directory(folder: Path, off: set = frozenset()):
    if not folder.is_dir():
        return
    for path in sorted(folder.iterdir()):
        if path.name.startswith(("_", ".")):
            continue
        _load_path(path, off)


def _load_path(path: Path, off: set = frozenset()) -> bool:
    """Read the manifest of one plugin file or package folder and import it; errors go to
    ``_registry.errors`` and the plugin's ``errors``. Returns whether it was imported."""
    if path.suffix == ".py":
        target = path
    elif path.is_dir() and (path / "__init__.py").exists():
        target = path / "__init__.py"
    else:
        return False
    plugin = Plugin(id=path.stem, kind="folder", origin=str(path))
    try:
        toml = path / MANIFEST_NAME if path.is_dir() else None
        plugin.apply_manifest(_read_toml(toml) if toml and toml.is_file() else file_manifest(target))
    except Exception as exc:
        plugin.errors.append(f"manifest: {type(exc).__name__}: {exc}")
    if not plugin.name:
        plugin.name = plugin.id
    if not _admit(plugin, off):
        return False
    if plugin.errors:   # an unreadable manifest also means the file would not import
        _registry.errors[str(path)] = plugin.errors[-1]
        return False
    module_name = f"ewald_plugin_{path.stem}"
    try:
        spec = importlib.util.spec_from_file_location(
            module_name, target, submodule_search_locations=[str(path)] if path.is_dir() else None)
        module = importlib.util.module_from_spec(spec)
        sys.modules[module_name] = module
        _loading.origin, _loading.plugin = str(path), plugin
        spec.loader.exec_module(module)
        plugin.loaded = True
    except Exception as exc:
        sys.modules.pop(module_name, None)
        _registry.errors[str(path)] = f"{type(exc).__name__}: {exc}"
        plugin.errors.append(_registry.errors[str(path)])
        return False
    finally:
        _loading.origin = _loading.plugin = None
    return True


def load_plugin_file(path) -> list[str]:
    """Import a plugin file (or package folder) from anywhere, e.g. in a notebook cell::

        from ewald.plugins import load_plugin_file
        load_plugin_file("local_strain.py")   # its @modifier classes become step cells

    Returns the names it registered (modifiers, readers, visuals, ...); raises if the
    import failed or the plugin is disabled or incompatible. Loading the same file again
    (an update) replaces its earlier entry, and so does a plugin with the same id whose file
    was removed (installing it again)."""
    load_plugins()
    before = {k: set(getattr(_registry, k)) for k in _REGISTRIES}
    path = Path(path).expanduser().resolve()
    _registry.errors.pop(str(path), None)
    for key in [k for k, p in _registry.plugins.items()
                if p.origin == str(path) or (p.kind != "package" and not Path(p.origin).exists())]:
        del _registry.plugins[key]          # this file's earlier entry, and removed files'
    if not _load_path(path, disabled()):
        raise ImportError(_registry.errors.get(str(path), f"{path} is not a .py file or a package folder, "
                                               "or it is disabled"))
    return [n for k in _REGISTRIES for n in getattr(_registry, k) if n not in before[k]]


def readers() -> dict[str, ReaderPlugin]:
    load_plugins()
    return dict(_registry.readers)


def scheme_reader(path) -> ReaderPlugin | None:
    """The reader registered for the scheme of ``path`` (``schemes=``), or None. A path with a
    registered scheme is not a file: it is not looked up locally or over SSH."""
    scheme = path_scheme(path)
    if scheme is None:
        return None
    return next((p for p in readers().values() if scheme in p.schemes), None)


def find_reader(path, format: str | None = None) -> ReaderPlugin:
    """The reader for ``format`` (name or alias; unknown names go to ASE), else the first by
    priority that recognises ``path``."""
    plugins = readers()
    by_scheme = scheme_reader(path)
    if by_scheme is not None and not format:
        return by_scheme
    if format:
        fmt = format.lower()
        for plugin in plugins.values():
            if fmt == plugin.name or fmt in plugin.aliases:
                return plugin
        return plugins["ase"]          # unknown names are ASE format names
    ranked = sorted((p for p in plugins.values() if p.priority is not None), key=lambda p: p.priority)
    for plugin in ranked:
        if plugin.matches(path):
            return plugin
    raise ValueError(f"no reader recognises {path}")


def open_reader(path, format: str | None = None, **kwargs) -> FrameReader:
    return find_reader(path, format).open(path, format=format, **kwargs)


def file_patterns(category: str | None = None) -> list[str]:
    """Glob patterns of all readers (of one ``category``), in priority order (for file dialogs)."""
    out = []
    for plugin in sorted(readers().values(), key=lambda p: (p.priority is None, p.priority or 0)):
        if category and plugin.category != category:
            continue
        out += [p for p in plugin.patterns if p not in out]
    return out


